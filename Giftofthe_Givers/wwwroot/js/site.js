function downloadCertificate() {

    const certificate = `
GIFT OF THE GIVERS

TAX CERTIFICATE
----------------------------

Thank you for your donation.

This document is a placeholder
tax certificate generated by the
Gift of the Givers prototype.

Donation status:
RECEIVED

This certificate is for
prototype demonstration purposes.
`;


    const blob = new Blob(
        [certificate],
        {
            type: "text/plain"
        }
    );


    const url =
        URL.createObjectURL(blob);


    const link =
        document.createElement("a");


    link.href = url;

    link.download =
        "Gift-of-the-Givers-Tax-Certificate.txt";


    document.body.appendChild(link);

    link.click();

    document.body.removeChild(link);


    URL.revokeObjectURL(url);
}